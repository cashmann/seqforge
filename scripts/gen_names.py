"""Generate sf-rom/src/names.rs from the decomps' include/tables/sequence_table.h.

Usage: gen_names.py <oot sequence_table.h> <mm sequence_table.h> <out.rs>
Names come from the NA_BGM_* identifiers, title-cased ("NA_BGM_GREAT_FAIRY"
becomes "Great Fairy"). Only names are taken; no game data.
"""
import re, sys

def names(path):
    out = []
    for line in open(path):
        line = line.split("//")[0]
        m = re.match(r"\s*DEFINE_SEQUENCE(_PTR)?\s*\(([^)]*)\)", line)
        if not m:
            continue
        args = [a.strip() for a in m.group(2).split(",")]
        ident = args[1]
        out.append(ident.removeprefix("NA_BGM_").replace("_", " ").title())
    return out

oot, mm = names(sys.argv[1]), names(sys.argv[2])
with open(sys.argv[3], "w") as f:
    f.write("// Generated by scripts/gen_names.py from the zeldaret/oot and zeldaret/mm\n")
    f.write("// sequence tables (identifiers only).\n\n")
    for var, lst in (("OOT", oot), ("MM", mm)):
        f.write(f"pub static {var}_SEQUENCE_NAMES: [&str; {len(lst)}] = [\n")
        for n in lst:
            f.write(f"    {n!r},\n".replace("'", '"'))
        f.write("];\n\n")
print(len(oot), len(mm))
